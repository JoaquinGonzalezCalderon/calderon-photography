const messages: Record<Lang, Messages> = { es, en, pt, zh }

const STORAGE_KEY = 'lang'

function initialLang(): Lang {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY)
    if (saved && saved in messages) return saved as Lang
  } catch { /* storage blocked: fall through */ }
  const browser = (navigator.languages?.[0] ?? navigator.language ?? '').toLowerCase()
  if (browser.startsWith('en')) return 'en'
  if (browser.startsWith('pt')) return 'pt'
  if (browser.startsWith('zh')) return 'zh'
  return 'es'
}

const I18nContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Messages }>({ lang: 'es', setLang: () => {}, t: es })

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = (next: Lang) => {
    setLangState(next)
    try { window.localStorage.setItem(STORAGE_KEY, next) } catch { /* keep it for this visit only */ }
  }
  useEffect(() => {
    document.documentElement.lang = langs.find((item) => item.id === lang)!.htmlLang
    document.querySelector('meta[name="description"]')?.setAttribute('content', messages[lang].meta.description)
  }, [lang])
  return <I18nContext.Provider value={{ lang, setLang, t: messages[lang] }}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
